from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect
BASE='http://127.0.0.1:8787'
OUT=Path('../docs/screenshots/cloudflare');OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1080},locale='pt-BR')
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE)
    page.get_by_label('E-mail',exact=True).fill('gestora@example.test')
    page.get_by_label('Senha',exact=True).fill('Fixture-Only-123')
    page.get_by_role('button',name='Entrar',exact=True).click()
    expect(page.locator('.stats')).to_be_visible()
    def tab(label):
        page.get_by_role('navigation',name='Navegação SIG-UHE').get_by_role('button',name=label,exact=True).click()
        expect(page.get_by_text('Carregando registros…',exact=True)).to_have_count(0)
    def save():
        page.get_by_role('button',name='Salvar registro',exact=True).click()
        expect(page.locator('fieldset.fields')).to_have_count(0,timeout=15000)
        expect(page.get_by_text('Carregando registros…',exact=True)).to_have_count(0)
    tab('UHEs e reservatórios')
    page.get_by_role('button',name='Cadastrar UHE',exact=True).click()
    page.get_by_label('Código da UHE',exact=True).fill('CN1')
    page.get_by_label('Nome da UHE',exact=True).fill('Canoas I')
    save()
    page.get_by_role('button',name='Cadastrar reservatório',exact=True).click()
    page.get_by_label('UHE',exact=True).select_option(label='Canoas I')
    page.get_by_label('Nome do reservatório',exact=True).fill('Reservatório Canoas I')
    save()
    print('PASS browser: SIGA session, UHE and reservoir persisted',flush=True)
    tab('Equipes')
    page.get_by_role('button',name='Cadastrar equipe',exact=True).click()
    page.get_by_label('Nome da equipe',exact=True).fill('Equipe ambiental')
    save()
    page.get_by_role('button',name='Perfil operacional',exact=True).click()
    page.get_by_label('Disponibilidade operacional',exact=True).select_option('available')
    page.get_by_label('Latitude da base operacional',exact=True).fill('-23')
    page.get_by_label('Longitude da base operacional',exact=True).fill('-50')
    page.get_by_label('Inspeção ambiental',exact=True).check()
    page.get_by_role('button',name='Adicionar intervalo',exact=True).click()
    page.get_by_label('Motivo da alteração operacional',exact=True).fill('Jornada inicial da equipe ambiental')
    save()
    expect(page.locator('table')).to_contain_text('Disponível')
    print('PASS browser: native Cloudflare team profile, skills and weekly schedule',flush=True)
    tab('Processos SIGA-CCU')
    expect(page.locator('table')).to_contain_text('CCU-0007')
    page.get_by_role('button',name='Vincular inspeção',exact=True).click()
    page.get_by_label('Reservatório de destino',exact=True).select_option(label='Reservatório Canoas I')
    page.get_by_label('Latitude do acesso terrestre',exact=True).fill('-23.01')
    page.get_by_label('Longitude do acesso terrestre',exact=True).fill('-50.01')
    save()
    tab('Solicitações')
    page.get_by_role('button',name='Detalhes',exact=True).click()
    expect(page.locator('.detail')).to_contain_text('SIGA-7')
    page.get_by_role('button',name='Emitir OS',exact=True).click()
    page.get_by_label('Latitude da base',exact=True).fill('-23.02')
    page.get_by_label('Longitude da base',exact=True).fill('-50.02')
    save()
    page.get_by_role('button',name='Detalhes',exact=True).click()
    expect(page.locator('.detail')).to_contain_text('OS-')
    page.screenshot(path=str(OUT/'solicitacoes.png'),full_page=True)
    tab('Visão geral')
    expect(page.locator('.stats article').filter(has_text='Ordens emitidas').locator('strong')).to_have_text('1')
    page.screenshot(path=str(OUT/'painel.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'Mobile overflow'
    page.screenshot(path=str(OUT/'celular.png'),full_page=True)
    print('PASS browser: source process linkage, actual order and responsive screenshots',flush=True)
    page.get_by_role('button',name='Sair',exact=True).click()
    expect(page.get_by_role('button',name='Entrar',exact=True)).to_be_visible()
    page.get_by_label('E-mail',exact=True).fill('inspetor@example.test')
    page.get_by_label('Senha',exact=True).fill('Fixture-Only-123')
    page.get_by_role('button',name='Entrar',exact=True).click()
    expect(page.locator('.stats')).to_be_visible()
    tab('Solicitações')
    expect(page.get_by_role('button',name='Nova solicitação',exact=True)).to_have_count(0)
    tab('Equipes')
    page.get_by_role('button',name='Perfil operacional',exact=True).click()
    expect(page.get_by_label('Latitude da base operacional',exact=True)).to_be_disabled()
    expect(page.get_by_role('button',name='Salvar registro',exact=True)).to_have_count(0)
    assert not errors,errors
    print('PASS browser: logout and read-only session; no JavaScript runtime errors',flush=True)
    browser.close()
